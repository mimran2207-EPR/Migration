"""Turn the development-structure workbook into src/content/concepts.ts.

  python scripts/import-concepts.py [path-to-xlsx]     (default: private/dev-structure-2026.xlsx)

Sheet "מושגים לפי שלבים": # | שלב ("N · title") | מושג (אנגלית) | הסבר בעברית | איך מיישמים.
Run it again whenever the workbook changes; the site reads only the generated file.
Requires: pip install openpyxl
"""

import json
import pathlib
import re
import sys

import openpyxl

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "private" / "dev-structure-2026.xlsx"
    ws = openpyxl.load_workbook(src, data_only=True)["מושגים לפי שלבים"]
    stages: dict[int, str] = {}
    concepts = []
    for row in ws.iter_rows(min_row=2, values_only=True):
        num, stage, term, he, how = (row + (None,) * 5)[:5]
        if not num or not term:
            continue
        m = re.match(r"\s*(\d+)\s*·\s*(.+)", str(stage))
        sid, stitle = int(m.group(1)), m.group(2).strip()
        stages[sid] = stitle
        concepts.append({"n": int(num), "stage": sid, "term": str(term).strip(), "he": str(he or "").strip(), "how": str(how or "").strip()})

    out = ROOT / "src" / "content" / "concepts.ts"
    out.write_text(
        "// Generated by scripts/import-concepts.py from the development-structure workbook. Do not edit by hand.\n"
        "export interface Concept { n: number; stage: number; term: string; he: string; how: string }\n"
        f"export const STAGES: Record<number, string> = {json.dumps(stages, ensure_ascii=False, indent=2)};\n"
        f"export const concepts: Concept[] = {json.dumps(concepts, ensure_ascii=False, indent=2)};\n",
        encoding="utf-8",
    )
    print(f"{len(concepts)} concepts in {len(stages)} stages → {out}")


if __name__ == "__main__":
    main()
